#!/bin/sh
# Generates docs/fixtures/big.md (> 1 MB) to test truncation.
out="$(dirname "$0")/../docs/fixtures/big.md"
{
  echo "# Big document"
  echo
  echo "Generated by scripts/make-big-md.sh. More than 1 MB: the preview must truncate it."
  i=1
  while [ "$i" -le 2700 ]; do
    echo
    echo "## Section $i"
    echo
    echo "Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore et dolore magna aliqua. Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut aliquip ex ea commodo consequat. Duis aute irure dolor in reprehenderit in voluptate velit esse cillum dolore eu fugiat nulla pariatur."
    echo
    echo "- item $i.a with \`inline code\`"
    echo "- item $i.b with **bold** text"
    if [ $((i % 50)) -eq 0 ]; then
      echo
      echo '```js'
      echo "const section = $i; // every 50th section has a fence"
      echo '```'
    fi
    i=$((i + 1))
  done
} > "$out"
wc -c "$out"
